export function profileFor(id: string): PersonProfile | undefined {
  const p = PROFILES[id];
  if (!p) return undefined;
  const merged: PersonProfile = { ...p };
  if (QUOTES[id]) merged.quote = QUOTES[id];
  if (STORIES[id]) merged.story = STORIES[id];
  return merged;
}
