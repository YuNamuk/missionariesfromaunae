export type ImgKind = "portrait" | "archive" | "ai";

export interface ColumnImage {
  src: string;
  alt: string;
  caption: string;
  /** 출처·성격 표기(사진/일러스트 구분) */
  credit: string;
  kind: ImgKind;
}
export interface ColumnSection {
  heading: string;
  paragraphs: string[];
  image?: ColumnImage;
}
export interface ColumnInterview {
  q: string;
  a: string;
}
/** 캐릭터 시트(기본 제공 초상 + 컬러본은 personId로 렌더, 아래는 카드 텍스트). */
export interface ColumnSheet {
  tagline: string;
  facts: [string, string][];
  family?: string;
}
export interface ResearchColumn {
  id: string;
  /** 사이트 인물 id(초상·컬러본·상세 링크의 근거) */
  personId: string;
  title: string;
  dek: string;
  /** 학생/반 크레딧 */
  author: string;
  hero: ColumnImage;
  sheet: ColumnSheet;
  lead: string[];
  sections: ColumnSection[];
  interview: ColumnInterview[];
  sources: string[];
}

